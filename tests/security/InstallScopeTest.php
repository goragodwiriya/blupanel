<?php

declare(strict_types=1);

/**
 * ขอบเขตของสิ่งที่ถูกติดตั้งลงเครื่องจริง
 *
 * `install.sh` คัดลอกเฉพาะโฟลเดอร์ที่ระบุไว้เป็นรายชื่อ — ไฟล์อื่นในโปรเจกต์
 * จึงไม่เคยไปอยู่บนเซิร์ฟเวอร์ของลูกค้า · ข้อนี้เป็นสิ่งที่ทำให้เก็บเครื่องมือของนักพัฒนา
 * ไว้ใน repo ได้อย่างปลอดภัย เช่น `tools/migrate-host.sh` ที่ย้ายข้อมูลข้ามเครื่อง —
 * เครื่องมือที่ทำงานนอกขอบเขตของ panel ไม่ควรไปอยู่บนเครื่องที่ให้บริการลูกค้า
 *
 * เทสต์นี้มีไว้เพราะรายชื่อโฟลเดอร์เป็นบรรทัดเดียวใน shell script ที่ใครก็เพิ่มได้
 * โดยไม่มีอะไรทัดทาน — และผลของการเพิ่มผิดจะไม่ปรากฏจนกว่าจะไปอยู่บนเครื่องจริงแล้ว
 */

group('InstallScope — ติดตั้งเฉพาะสิ่งที่ต้องรันจริงเท่านั้น');

test('install.sh ต้องไม่คัดลอกเครื่องมือของนักพัฒนาไปเครื่องลูกค้า', static function (): void {
    $installer = (string) file_get_contents(PHPCP_ROOT.'/install.sh');

    assertTrue(
        preg_match('/for dir in ([^;]+); do/', $installer, $matches) === 1,
        'ไม่พบบรรทัดที่ระบุรายชื่อโฟลเดอร์ที่จะคัดลอก — โครงสร้าง install.sh เปลี่ยนไปแล้ว',
    );

    $copied = preg_split('/\s+/', trim($matches[1])) ?: [];

    // โฟลเดอร์ที่ห้ามติดตั้ง พร้อมเหตุผลของแต่ละตัว
    $forbidden = [
        'tools' => 'สคริปต์ย้ายข้อมูลและซ่อมระบบของนักพัฒนา — ทำงานนอกขอบเขตของ panel',
        'tests' => 'ชุดทดสอบ ไม่มีเหตุผลให้อยู่บนเครื่องที่ให้บริการ',
        'var' => 'ข้อมูลของสภาพแวดล้อมนักพัฒนา รวมถึงฐานข้อมูลทดสอบ',
    ];

    foreach ($forbidden as $dir => $reason) {
        assertTrue(!in_array($dir, $copied, true), "install.sh ต้องไม่คัดลอก {$dir}/ — {$reason}");
    }

    // และของที่ต้องมีจริงต้องยังอยู่ครบ ไม่ใช่ลบเกินจนติดตั้งแล้วใช้ไม่ได้
    foreach (['bin', 'src', 'templates', 'db', 'public'] as $required) {
        assertTrue(in_array($required, $copied, true), "install.sh ต้องคัดลอก {$required}/");
    }
});

test('เครื่องมือของนักพัฒนาต้องอยู่ใน tools/ ไม่ใช่รูทของโปรเจกต์', static function (): void {
    // ไฟล์ที่รูทถูกมองข้ามได้ง่ายตอนทบทวนว่าอะไรบ้างที่ถูกติดตั้ง — การรวมไว้ที่เดียว
    // ทำให้กฎ "tools/ ไม่ถูกติดตั้ง" ครอบคลุมเครื่องมือทุกตัวโดยอัตโนมัติ
    $stray = glob(PHPCP_ROOT.'/*.sh') ?: [];
    $allowed = ['install.sh'];

    foreach ($stray as $path) {
        $name = basename($path);

        assertTrue(
            in_array($name, $allowed, true),
            "{$name} อยู่ที่รูทของโปรเจกต์ — ย้ายไป tools/ เพื่อให้อยู่ในขอบเขตที่ไม่ถูกติดตั้ง",
        );
    }
});
