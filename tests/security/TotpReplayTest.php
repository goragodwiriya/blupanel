<?php

declare(strict_types=1);

/**
 * รหัส 2FA หนึ่งรหัสต้องใช้ได้ครั้งเดียว
 *
 * **สิ่งที่เทสต์นี้กันไว้:** หน้าต่างที่กว้าง ±1 ช่วง (กันนาฬิกาคลาดเคลื่อน) ทำให้รหัส
 * หนึ่งรหัสใช้ได้นานราว 90 วินาที · เดิมไม่มีใครจำว่ารหัสไหนถูกใช้ไปแล้ว รหัสเดิมจึงใช้
 * ซ้ำได้ตลอดช่วงนั้น
 *
 * ทำไมสำคัญกว่าที่เห็น: 2FA มีไว้กันกรณีที่**รหัสผ่านหลุดไปแล้ว** · ผู้โจมตีที่เห็นรหัส
 * หกหลักได้ครั้งเดียว (แอบดูจอ, มัลแวร์อ่านคลิปบอร์ด, ฟิชชิงที่ผู้ใช้กรอกให้) จึงต้อง
 * ไม่เหลือเวลาอีกเกือบนาทีครึ่งไว้ใช้รหัสเดียวกันซ้ำหลังเจ้าตัวใช้เข้าระบบไปแล้ว
 */

use Phpcp\Security\Totp;

group('TOTP — รหัสเดิมต้องใช้ซ้ำไม่ได้');

/** รหัสของช่วงเวลาที่ระบุ — เรียกเมธอดภายในเพื่อทดสอบขอบของหน้าต่างให้ครบ */
function totpCodeAt(string $secret, int $counter): string
{
    $method = new ReflectionMethod(Totp::class, 'codeAt');
    $method->setAccessible(true);

    return (string) $method->invoke(null, $secret, $counter);
}

test('รหัสที่ใช้ไปแล้วต้องใช้ซ้ำไม่ได้ แม้จะยังไม่หมดอายุ', static function (): void {
    $secret = Totp::generateSecret();
    $code = Totp::currentCode($secret);

    $first = Totp::verifyAt($secret, $code);

    // ไม่ยืนยันตัวเลขเป๊ะ ๆ เพราะเวลาอาจข้ามขอบช่วง 30 วินาทีระหว่างสองบรรทัดนี้ได้จริง
    // — เทสต์ที่ล้มเป็นครั้งคราวเองคือเทสต์ที่คนจะเลิกเชื่อ
    assertTrue($first !== null, 'ครั้งแรกต้องผ่านและคืนหมายเลขช่วงเวลาที่ตรง');

    assertSame(
        null,
        Totp::verifyAt($secret, $code, $first),
        'รหัสเดิมที่ถูกใช้ไปแล้วต้องไม่ผ่านอีก — นี่คือทั้งหมดของเรื่องนี้',
    );
});

test('รหัสของช่วงก่อนหน้าที่ถูกใช้แล้ว ต้องไม่ผ่านด้วย', static function (): void {
    // ผู้โจมตีที่ได้รหัสของช่วงก่อนหน้ามา ต้องไม่ได้อะไรจากหน้าต่างที่เผื่อไว้
    // สำหรับนาฬิกาคลาดเคลื่อน
    $secret = Totp::generateSecret();
    $now = intdiv(time(), 30);

    assertSame(
        null,
        Totp::verifyAt($secret, totpCodeAt($secret, $now - 1), $now),
        'ช่วงที่เก่ากว่าหรือเท่ากับที่ใช้ไปแล้ว ต้องถูกปฏิเสธทั้งหมด',
    );
});

test('รหัสของช่วงถัดไปต้องยังใช้ได้ — ด่านต้องไม่ล็อกคนใช้จริงออก', static function (): void {
    /*
     * เครื่องของผู้ใช้ที่นาฬิกาเร็วกว่าเซิร์ฟเวอร์เล็กน้อย จะส่งรหัสของช่วงถัดไปมา
     * ถ้าด่านกัน replay เข้มจนปฏิเสธอันนั้นด้วย ผู้ใช้กลุ่มนั้นจะเข้าระบบไม่ได้เลย
     * ซึ่งเป็นความเสียหายที่หนักกว่าปัญหาที่กำลังแก้
     */
    $secret = Totp::generateSecret();
    $now = intdiv(time(), 30);

    assertSame(
        $now + 1,
        Totp::verifyAt($secret, totpCodeAt($secret, $now + 1), $now),
        'ช่วงถัดไปต้องยังผ่านได้หลังใช้ช่วงปัจจุบันไปแล้ว',
    );
});

test('verify() แบบเดิมต้องยังทำงานเหมือนเดิม', static function (): void {
    // ยังมีผู้เรียกที่ไม่ได้เก็บหมายเลขช่วงเวลา (เช่นตอนเปิดใช้งาน 2FA ครั้งแรก)
    $secret = Totp::generateSecret();

    assertTrue(Totp::verify($secret, Totp::currentCode($secret)), 'รหัสที่ถูกต้องต้องผ่าน');
    assertTrue(!Totp::verify($secret, '000000'), 'รหัสมั่วต้องไม่ผ่าน');
    assertTrue(!Totp::verify($secret, 'abc'), 'ข้อความที่ไม่ใช่ตัวเลขหกหลักต้องไม่ผ่าน');
});
