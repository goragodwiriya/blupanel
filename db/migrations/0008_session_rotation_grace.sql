-- ช่วงผ่อนผันตอนหมุน session id
--
-- ปัญหาที่แก้: การหมุน id ทำให้ id เดิม **ใช้ไม่ได้ทันที** ซึ่งใช้ได้กับ UI ที่ยิงคำขอ
-- ทีละหนึ่ง แต่ SPA ยิงหลายคำขอพร้อมกันต่อหนึ่งหน้า · คำขอที่ออกไปก่อนหน้าเสี้ยววินาที
-- ยังถือคุกกี้เดิมอยู่ พอมาถึงเซิร์ฟเวอร์หลังการหมุนก็หา session ไม่เจอ แล้วถูกตีเป็น
-- "ล็อกอินหมดอายุ" ทั้งที่ผู้ใช้ไม่ได้ทำอะไรผิดเลย
--
-- เก็บ hash ของ id เดิมไว้ชั่วคราวเพื่อให้คำขอที่ค้างอยู่ใช้ต่อได้จนกว่าจะพ้นช่วงผ่อนผัน
-- ซึ่งสั้นมาก (ไม่กี่สิบวินาที) จึงไม่ได้ยืดอายุคุกกี้ที่รั่วไปอย่างมีนัยสำคัญ

ALTER TABLE sessions ADD COLUMN prev_id_hash TEXT;
ALTER TABLE sessions ADD COLUMN prev_until   INTEGER NOT NULL DEFAULT 0;

-- ต้องมีดัชนีเพราะทุกคำขอที่ถือคุกกี้เก่าจะค้นด้วยคอลัมน์นี้
CREATE INDEX idx_sessions_prev ON sessions(prev_id_hash);
