-- 0011_disk_quota_state — สถานะแจ้งเตือนโควตาดิสก์ล่าสุดของแต่ละบัญชี (PLAN-V2 เฟส E2)
--
-- ต่างจาก expiry_notifications ตรงที่วันหมดอายุเดินไปทางเดียว (นับถอยหลังสู่วันที่ตายตัว)
-- แต่การใช้ดิสก์ขึ้นลงได้ตลอดเวลา — ถ้าใช้ตาราง "แจ้งแล้วห้ามแจ้งซ้ำ" แบบเดียวกับ
-- expiry_notifications ตรง ๆ บัญชีที่เคยแตะ 80% แล้วลดลงจะไม่มีวันได้รับแจ้งเตือนอีกเลย
-- แม้จะเต็มขึ้นมาใหม่ในอีกหกเดือนข้างหน้า จึงเก็บแค่ "ระดับล่าสุดที่แจ้งไปแล้ว" หนึ่งค่า
-- ต่อผู้ใช้ แล้วเทียบทุกรอบว่าระดับปัจจุบันสูงกว่าค่าที่เก็บไว้หรือไม่ (แจ้งเมื่อสูงขึ้น
-- เท่านั้น ไม่แจ้งตอนลดลง — ปฏิบัติตามหลักการของ Notifier: "แจ้งเฉพาะเรื่องที่ต้องลงมือทำ")

CREATE TABLE disk_quota_state (
    user_id       INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,

    -- 0 = ยังไม่เคยแจ้ง (หรือกลับมาต่ำกว่า 80% แล้ว) · 80/90/100 = ระดับล่าสุดที่แจ้งไปแล้ว
    last_threshold INTEGER NOT NULL DEFAULT 0,

    checked_at    INTEGER NOT NULL,
    updated_at    INTEGER NOT NULL
);
