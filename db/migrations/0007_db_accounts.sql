-- 0007_db_accounts — บัญชี MariaDB ประจำผู้ใช้ สำหรับเข้า phpMyAdmin โดยไม่ต้องพิมพ์รหัส
--
-- ปัญหาเดิม
-- ---------
-- panel เก็บรหัสผ่านของ panel เป็น Argon2id (ย้อนกลับไม่ได้) ส่วนรหัสผ่านของผู้ใช้ MariaDB
-- ถูกสุ่มตอนสร้างฐานข้อมูลแล้วแสดงครั้งเดียว **ไม่เก็บไว้เลย** · ผลคือลูกค้าต้องจดรหัสนั้น
-- ไว้เองซึ่งในทางปฏิบัติแปลว่าไปอยู่ในไฟล์ text บนเครื่องตัวเอง หรือถูกตั้งใหม่ซ้ำ ๆ
-- ทุกครั้งที่ลืม และ phpMyAdmin ก็กลายเป็นหน้าล็อกอินที่สองที่ไม่เกี่ยวกับ panel เลย
--
-- วิธีแก้
-- ------
-- ให้แต่ละผู้ใช้มีบัญชี MariaDB ประจำตัวหนึ่งบัญชี รหัสสุ่มโดยระบบและ**ไม่เคยผ่านตาผู้ใช้**
-- เก็บแบบเข้ารหัสด้วย sodium secretbox ด้วยคีย์เดียวกับที่ใช้เก็บ TOTP secret
-- (อยู่ใน /etc/phpcp/config.php ซึ่งแยกไฟล์จากฐานข้อมูล) แล้วให้ panel เปิด session
-- ของ phpMyAdmin ให้ผ่าน auth_type = signon
--
-- สิ่งที่ต้องยอมรับอย่างตรงไปตรงมา
-- ------------------------------
-- นี่คือความลับชนิดใหม่ที่ระบบต้องปกป้อง — เดิมไม่มีรหัสผ่าน MariaDB เก็บอยู่ที่ไหนเลย
-- เหตุผลที่ยังคุ้ม: agent รันด้วยสิทธิ์ root และเข้า MariaDB ผ่าน unix_socket ได้เต็มที่อยู่แล้ว
-- การเก็บรหัสนี้จึงไม่ได้เพิ่ม "สิ่งที่ผู้บุกรุกที่ยึด agent ได้แล้วทำได้" แม้แต่อย่างเดียว
-- แต่แลกมาด้วยการที่ลูกค้าเลิกจดรหัสฐานข้อมูลใส่ไฟล์ text ซึ่งอันตรายกว่ามากในทางปฏิบัติ
-- · รหัสหมุนได้ทุกเมื่อด้วย db.account.rotate โดยผู้ใช้ไม่รู้สึกอะไรเลย

CREATE TABLE db_accounts (
    user_id      INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,

    -- ชื่อผู้ใช้ MariaDB — ตรงกับชื่อบัญชีระบบเสมอ เก็บซ้ำไว้เพื่อให้ตรวจสอบย้อนหลังได้
    -- ว่าแถวนี้เคยผูกกับบัญชีชื่ออะไร แม้ผู้ใช้จะถูกลบไปแล้ว
    mysql_user   TEXT    NOT NULL UNIQUE,
    host         TEXT    NOT NULL DEFAULT 'localhost',

    -- ciphertext ของ sodium secretbox (base64) — อ่านความหมายได้เฉพาะฝั่ง agent
    password_enc TEXT    NOT NULL,

    created_at   INTEGER NOT NULL,
    rotated_at   INTEGER
);

CREATE INDEX idx_db_accounts_user ON db_accounts(mysql_user);
