-- 0013_sftp_access — เปิด/ปิด SFTP ต่อบัญชีโฮสติ้ง (PLAN-V2 เฟส E4)
--
-- **หนึ่งบัญชีโฮสติ้ง = หนึ่ง SFTP login** ไม่ใช่หลายบัญชีย่อยต่อเว็บอย่างที่แผนเดิมร่างไว้
-- เหตุผล: ตั้งแต่ migration 0006 หน่วยของการแยกสิทธิ์คือ**ผู้ใช้** (หนึ่งผู้ใช้ = หนึ่ง uid
-- = หนึ่งบ้าน = หลายเว็บ) การสร้างบัญชี SFTP เพิ่มต่อเว็บจึงไม่ได้แยกอะไรเพิ่มเลย เพราะทุกเว็บ
-- ของผู้ใช้คนเดียวกันใช้ uid เดียวกันอยู่แล้ว — และการทำให้บัญชีที่สองเข้าถึงไฟล์เว็บได้
-- ต้องรื้อโมเดลสิทธิ์ไฟล์ทั้งระบบ (ไฟล์เป็น <user>:www-data เพื่อให้เว็บเซิร์ฟเวอร์เดินผ่าน
-- ไดเรกทอรี 0750 ได้) ซึ่งขัดกับ §7.1 ข้อ 2 "ห้ามลดชั้นความปลอดภัยใด ๆ ที่มีอยู่"
--
-- `quota_ftp_users` จึงถูกตีความใหม่เป็น **สวิตช์** ไม่ใช่จำนวน:
--   0  = ห้ามใช้ SFTP เลย
--   >0 หรือ -1 = เปิดได้ (หนึ่งบัญชีเสมอ)
-- ไม่ลบคอลัมน์ทิ้งเพราะยังใช้บอกสิทธิ์ตามแพ็กเกจได้ตรงตัว และการลบคอลัมน์ทำให้ค่าที่ผู้ดูแล
-- ตั้งไว้แล้วหายไปโดยไม่ได้อะไรกลับมา

-- NULL ไม่ได้ — สถานะนี้ต้องตอบได้เสมอว่าเปิดหรือปิด ไม่มี "ไม่รู้"
ALTER TABLE users ADD COLUMN sftp_enabled INTEGER NOT NULL DEFAULT 0;

-- เวลาที่เปิดใช้งานล่าสุด — ใช้ตอบคำถาม "ใครเปิด SFTP ไว้บ้างและตั้งแต่เมื่อไร" ตอนตรวจสอบ
-- ความปลอดภัย · NULL = ยังไม่เคยเปิด
ALTER TABLE users ADD COLUMN sftp_enabled_at INTEGER;
