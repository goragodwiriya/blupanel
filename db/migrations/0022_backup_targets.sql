-- 0022_backup_targets — ผู้ดูแลเลือกว่าบัญชีไหนถูกสำรองอัตโนมัติบ้าง
--
-- **ปัญหาที่แก้:** ตารางเวลาสำรองเดิมเป็นแถวในตาราง `scheduled_jobs` หนึ่งแถวต่อ
-- หนึ่งเว็บหนึ่งชนิด · ผู้ดูแลที่มีลูกค้าห้าสิบรายต้องสร้างและดูแลตารางเวลาเป็นร้อยชุด
-- ด้วยมือ แล้วทุกครั้งที่มีเว็บใหม่ก็ต้องจำว่าต้องไปเพิ่มอีกชุด — ระบบที่ "ลืมสำรอง
-- เว็บใหม่เงียบ ๆ" คือระบบสำรองที่ใช้ไม่ได้จริง
--
-- **ที่มาแทน:** สวิตช์สองตัวบนบัญชี แล้ว cron ตัวเดียวของทั้งเครื่องเดินตามสวิตช์นั้น
-- (PLAN-BACKUP-V2 ข้อ B3, B6, B10) · เว็บใหม่ของบัญชีที่เปิดสวิตช์ไว้ถูกสำรองทันที
-- ในรอบถัดไปโดยไม่ต้องมีใครไปตั้งอะไรเพิ่ม
--
-- **แยกไฟล์กับฐานข้อมูลออกจากกัน** (ข้อ B8) — เว็บสแตติกไม่มีฐานข้อมูลให้สำรอง และ
-- บางบัญชีต้องการเฉพาะฐานข้อมูลเพราะไฟล์เว็บอยู่ใน git อยู่แล้ว · การมัดรวมเป็นสวิตช์
-- เดียวแปลว่าทั้งสองกลุ่มต้องจ่ายพื้นที่ให้กับของที่ไม่ได้ต้องการ
--
-- **ค่าเริ่มต้นเป็น 0 ทั้งคู่** (ข้อ B7) — ไฟล์สำรองนับในโควตาของลูกค้าแล้ว การเปิดให้
-- ทุกบัญชีโดยอัตโนมัติเท่ากับหักพื้นที่ของเขาไปโดยที่ไม่มีใครสั่ง · บัญชีที่มีอยู่แล้ว
-- จึงไม่ขยับด้วยเหตุผลเดียวกัน

ALTER TABLE users ADD COLUMN backup_files INTEGER NOT NULL DEFAULT 0
    CHECK(backup_files IN (0, 1));

ALTER TABLE users ADD COLUMN backup_database INTEGER NOT NULL DEFAULT 0
    CHECK(backup_database IN (0, 1));
