-- 0016_site_rate_limit — จำกัดอัตราคำขอต่อเว็บไซต์ (PLAN-V2 เฟส E5)
--
-- **ปัญหาที่ต้องแก้:** เทมเพลต vhost ของลูกค้าไม่มีการป้องกัน L7 DoS เลย
-- คนเดียวยิง `/wp-login.php` รัว ๆ ทำให้ PHP-FPM pool ของเว็บนั้นเต็มทุก worker
-- แล้วเว็บล่มทั้งที่แบนด์วิดท์กับ CPU ของเครื่องยังเหลือเฟือ
--
-- **ทำไมใช้ fail2ban ไม่ใช่โมดูลของเว็บเซิร์ฟเวอร์:**
--
--   · Apache ไม่มีเครื่องมือจำกัด "จำนวนคำขอ" ในตัว — `mod_ratelimit` ที่แผนเดิมระบุไว้
--     จำกัด**แบนด์วิดท์** (KB/s ต่อ connection) เท่านั้น คนยิง 10,000 req/s ยังยิงได้ครบ
--     แค่ได้ข้อมูลกลับช้าลง · การใส่แล้วบอกว่า "มี rate limit" คือความปลอดภัยหลอก
--   · `mod_evasive` ต้องติดตั้งเพิ่ม และนับแยกต่อ child process (ไม่แชร์สถานะกัน)
--     เกณฑ์จริงจึงกลายเป็นค่าที่ตั้งไว้คูณจำนวน child ซึ่งอธิบายให้ผู้ดูแลเข้าใจยากมาก
--   · fail2ban ทำงานอยู่บนเครื่องอยู่แล้ว ใช้โค้ดชุดเดียวได้ทั้ง Apache และ nginx
--     (อ่าน access log เหมือนกัน) และบล็อกที่ firewall ซึ่งถูกกว่าให้เว็บเซิร์ฟเวอร์รับคำขอ
--
-- **ข้อแลกเปลี่ยนที่ต้องรู้และต้องบอกผู้ดูแลบนหน้าจอ:**
--
--   1. **ตอบสนองช้ากว่าโมดูลในตัว** — fail2ban อ่าน log เป็นรอบ ไม่ใช่ทันทีที่คำขอเข้ามา
--      · คำขอชุดแรกที่เกินเกณฑ์จะผ่านไปถึงเว็บก่อนเสมอ
--   2. **การแบนมีผลทั้งเครื่อง ไม่ใช่เฉพาะเว็บนั้น** — fail2ban สั่ง firewall ซึ่งไม่รู้จัก
--      vhost · IP ที่ยิงเว็บ A จนโดนแบน จะเข้าเว็บ B ของลูกค้าอีกรายไม่ได้ด้วย
--      นี่เป็นเหตุผลที่ค่าเริ่มต้นต้องหลวมพอที่คนใช้งานปกติจะไม่มีวันชน

CREATE TABLE site_rate_limits (
    site_id     INTEGER NOT NULL PRIMARY KEY REFERENCES sites(id) ON DELETE CASCADE,

    -- ปิดไว้เป็นค่าเริ่มต้นเสมอ — การเปิดให้อัตโนมัติทุกเว็บแปลว่าเว็บที่มีทราฟฟิกสูง
    -- โดยชอบธรรม (API, เว็บข่าว) จะถูกแบนตัวเองในวันที่ติดตั้ง โดยไม่มีใครสั่ง
    enabled     INTEGER NOT NULL DEFAULT 0 CHECK(enabled IN (0,1)),

    -- จำนวนคำขอสูงสุดจาก IP เดียวภายใน `window_seconds` วินาที
    max_requests   INTEGER NOT NULL DEFAULT 300 CHECK(max_requests BETWEEN 10 AND 100000),
    window_seconds INTEGER NOT NULL DEFAULT 60  CHECK(window_seconds BETWEEN 10 AND 3600),

    -- แบนนานเท่าไร (วินาที) — สั้นไว้ก่อนดีกว่า เพราะการแบนผิดพลาดกระทบทั้งเครื่อง
    ban_seconds    INTEGER NOT NULL DEFAULT 600 CHECK(ban_seconds BETWEEN 60 AND 86400),

    -- IP ที่ไม่ถูกนับเลย คั่นด้วยช่องว่าง — เก็บเป็นข้อความเพราะ fail2ban รับรูปแบบนี้ตรง ๆ
    -- (รองรับทั้ง IP เดี่ยวและ CIDR) · ผู้ดูแลใส่ IP สำนักงานหรือ uptime monitor ไว้ที่นี่
    ignore_ips  TEXT    NOT NULL DEFAULT '',

    created_at  INTEGER NOT NULL,
    updated_at  INTEGER NOT NULL
);
