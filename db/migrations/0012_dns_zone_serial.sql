-- BIND9 (และ resolver/secondary ทุกตัว) ตัดสินว่า zone มีอะไรใหม่จากเลขนี้เพียงอย่างเดียว
-- ต้องเพิ่มขึ้นอย่างเดียวเสมอ ห้ามซ้ำหรือย้อนกลับ ไม่งั้น secondary/resolver บางตัวจะไม่ดึง
-- ข้อมูลใหม่ไปเลยเพราะคิดว่าเป็นสำเนาที่เก่ากว่าที่ถืออยู่ — เก็บไว้ในฐานข้อมูลของ panel เอง
-- แทนที่จะอ่านจากไฟล์ zone เดิม เพราะไฟล์อาจถูกลบ/ย้าย/ยังไม่เคยเขียนเลยก็ได้
--
-- 0 = ยังไม่เคยส่งออกเป็น zone จริงเลย (ไม่มีไฟล์ในดิสก์) — ค่าที่ dns.zone_write ใช้
-- ตัดสินว่าต้องเพิ่ม stanza ใหม่ใน named.conf.local ด้วยหรือแค่เขียนทับไฟล์ zone เดิม
