-- 0026_metrics_peaks — เก็บค่าสูงสุดของทุกตัววัด ไม่ใช่แค่ CPU
--
-- **ปัญหาที่แก้:** กราฟย้อนหลังมีไว้ตอบคำถามเดียวคือ "ช่วงไหนผิดปกติ" แต่ค่าที่วาดคือ
-- ค่าเฉลี่ย ซึ่งกลบสิ่งนั้นทิ้งพอดี — ช่วง 7 วันหนึ่งจุดครอบ 12 ชั่วโมง เครื่องที่ตัน 100%
-- อยู่ 20 นาทีจึงโผล่มาเป็นเนิน 3% มองไม่ออกเลยว่ามีอะไรเกิดขึ้น
--
-- 0014 เก็บ `cpu_peak` ไว้แล้วด้วยเหตุผลนี้ตรง ๆ แต่หยุดอยู่แค่ CPU ตัวเดียว
--
-- **ทำไมต้องเป็นคอลัมน์ ไม่ใช่คำนวณตอนอ่าน:** `metrics.record` เขียนนาทีละครั้ง แถวชั้น
-- 'minute' จึงมีตัวอย่างเดียว ค่าสูงสุดของชั้นนั้นคือค่าที่วัดได้จริง ๆ · แต่พอยุบขึ้นชั้น
-- 'hour' ค่าที่เหลือคือค่าเฉลี่ยของ 60 ตัวอย่าง พีคที่เกิดในชั่วโมงนั้นหายไปแล้วอย่างถาวร ·
-- การ MAX() ตอนอ่านจึงได้แค่ "ค่าเฉลี่ยรายชั่วโมงที่สูงที่สุด" ไม่ใช่ค่าสูงสุดจริง —
-- ต่างกันคนละเรื่องพอดีกับสิ่งที่กราฟถาม ค่าสูงสุดจึงต้องถูกพาขึ้นชั้นไปด้วยตอนยุบ
--
-- **การเติมค่าย้อนหลัง:** แถวเดิมไม่มีค่าสูงสุดให้กู้ ค่าเฉลี่ยคือข้อมูลเดียวที่มี จึงเติม
-- ด้วยค่าเฉลี่ยของแถวนั้นเอง — ชั้น 'minute' ค่านี้ถูกต้องเป๊ะ (ตัวอย่างเดียว) ส่วนชั้น
-- 'hour'/'day' ต่ำกว่าความจริง ซึ่งหมดไปเองภายใน 30 วัน/1 ปีตามอายุของแต่ละชั้น

