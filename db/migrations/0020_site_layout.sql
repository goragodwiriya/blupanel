-- 0020_site_layout — เลือกได้ว่าไฟล์เว็บของผู้ใช้แต่ละคนวางแบบไหน
--
-- **ปัญหา:** เส้นทางไฟล์เป็นสูตรตายตัวสูตรเดียวมาตลอด —
-- `<users_dir>/<user>/domains/<domain>/public` — เปลี่ยนได้แค่ส่วนหน้า (`sites.users_dir`)
-- แต่รูปทรงข้างในเปลี่ยนไม่ได้เลย · ผู้ที่ย้ายมาจาก cPanel/DirectAdmin จึงได้เส้นทางที่
-- ไม่ตรงกับที่ลูกค้าเดิมคุ้นเคย และสคริปต์ deploy ทุกตัวของลูกค้าต้องแก้ตาม
--
-- **ทางเลือกที่เพิ่ม:**
--
--   phpcp   `<users_dir>/<user>/domains/<domain>/public`   (เดิม · ยังเป็นค่าเริ่มต้น)
--   cpanel  `<users_dir>/<user>/public_html`               สำหรับโดเมนหลักของบัญชี
--           `<users_dir>/<user>/<domain>`                  สำหรับโดเมนที่เพิ่มทีหลัง
--
-- **ตั้งได้ต่อผู้ใช้ ไม่ใช่ต่อระบบ** เพราะเครื่องหนึ่งรับลูกค้าที่ย้ายมาจากคนละที่ได้
-- · ค่าว่างใน `site_layout` แปลว่า "ตามค่าเริ่มต้นของระบบ" (ค่าตั้ง `sites.layout`)
-- ไม่ใช่ "phpcp" — ผู้ดูแลที่เปลี่ยนค่าเริ่มต้นของระบบภายหลังจึงมีผลกับบัญชีที่ยัง
-- ไม่เคยเลือกเอง โดยไม่ไปแตะบัญชีที่เลือกไว้ชัดเจนแล้ว
--
-- **`main_domain` จำเป็นเพราะอะไร:** เลย์เอาต์ cpanel ต้องตอบให้ได้ว่าโดเมนไหนคือ
-- "โดเมนหลักของบัญชี" ที่ได้ `public_html` ไป · คำถามนี้ตอบจากข้อมูลที่มีอยู่ไม่ได้
-- เพราะผู้ใช้หนึ่งคนมีได้หลายเว็บและลำดับ id ไม่ใช่คำสัญญาอะไร · เก็บไว้ตรง ๆ ตอนสร้าง
-- เว็บแรกแล้วไม่ต้องเดาอีกเลย — และผู้ดูแลมองเห็น/แก้ได้จากหน้าจอ ต่างจากกฎที่ซ่อนอยู่ในโค้ด
--
-- เว็บที่มีอยู่แล้วไม่ขยับ: ทุกแถวได้ `site_layout = ''` ซึ่งตกไปที่ค่าเริ่มต้นของระบบ
-- ที่ยังเป็น `phpcp` · **ไม่มีไฟล์ใดถูกย้ายโดย migration นี้** การย้ายจริงเป็นงานของ
-- `user.set_layout` ที่ผู้ดูแลสั่งเองเมื่อพร้อม เพราะมันแตะไฟล์ของเว็บที่ให้บริการอยู่

ALTER TABLE users ADD COLUMN site_layout TEXT NOT NULL DEFAULT ''
    CHECK(site_layout IN ('', 'phpcp', 'cpanel'));

ALTER TABLE users ADD COLUMN main_domain TEXT NOT NULL DEFAULT '';

-- โดเมนหลักของบัญชีที่มีเว็บอยู่แล้ว = เว็บที่สร้างก่อนที่สุดของเจ้าของคนนั้น
--
-- ตอนนี้ยังไม่มีผลกับเส้นทางใด ๆ เพราะทุกบัญชียังใช้เลย์เอาต์ phpcp — แต่ต้องเติมไว้
-- ตั้งแต่ตอนนี้ ไม่งั้นบัญชีที่เปลี่ยนไป cpanel ภายหลังจะไม่มีโดเมนหลักให้ชี้
-- แล้วทุกเว็บจะตกไปอยู่ `<home>/<domain>` โดยไม่มี `public_html` เลยสักอัน
UPDATE users SET main_domain = (
    SELECT s.primary_domain FROM sites s
    WHERE s.owner_user_id = users.id
    ORDER BY s.created_at, s.id
    LIMIT 1
)
WHERE EXISTS (SELECT 1 FROM sites s WHERE s.owner_user_id = users.id);
