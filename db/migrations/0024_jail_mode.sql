-- 0024_jail_mode — jail ต้องเลือกได้ว่า "แบน" หรือ "แจ้งเตือนแล้วให้คนตัดสินใจ"
--
-- **ปัญหาที่แก้:** การจำกัดอัตราคำขอมีแค่สองสถานะคือเปิดกับปิด และ "เปิด" แปลว่า
-- แบนอัตโนมัติที่ firewall เสมอ · ผู้ดูแลที่อยากเห็นก่อนว่าระบบจับอะไรได้บ้าง
-- ก่อนจะมอบอำนาจตัดคนออกจากเครื่องให้มันทำเอง ไม่มีทางเลือกนั้นเลย
--
-- ทำไมเรื่องนี้สำคัญกับที่นี่เป็นพิเศษ: ลูกค้าบางรายเป็นโรงเรียนที่คนทั้งโรงเรียน
-- ออกเน็ตผ่าน IP เดียวกัน · การแบนหนึ่งครั้งจึงไม่ได้ตัดคนคนเดียวแต่ตัดทั้งองค์กร
-- และเพราะ fail2ban สั่ง firewall ซึ่งไม่รู้จัก vhost เขาจะเข้าเว็บของลูกค้ารายอื่น
-- บนเครื่องเดียวกันไม่ได้ด้วย · โหมดแจ้งเตือนให้ข้อมูลเท่ากันโดยไม่ตัดสินใจแทนคน
--
-- ค่าเริ่มต้นของ **แถวที่มีอยู่แล้ว** เป็น 'ban' โดยตั้งใจ — เว็บที่เปิดการจำกัดอัตรา
-- ไว้ก่อนหน้านี้ถูกเปิดโดยเข้าใจว่าจะแบน การเปลี่ยนความหมายย้อนหลังจะทำให้การป้องกัน
-- ที่เขาเลือกไว้หายไปเงียบ ๆ · ส่วนค่าเริ่มต้นของ**ของใหม่** ที่หน้าจอเสนอคือ 'notify'
-- ซึ่งเป็นคนละเรื่องกันและอยู่ในชั้นแอป ไม่ใช่ในสคีมา

