-- 0021_drop_display_only_names — ตัดชื่อที่มีไว้แสดงผลอย่างเดียวทิ้ง
--
-- **`sites.name`** — ผู้สร้างเว็บต้องคิดชื่อให้เว็บทุกครั้งทั้งที่ไม่มีอะไรใช้มันเลย
-- นอกจากเอาไปแสดงข้าง ๆ ชื่อโดเมน · ไม่ได้ถูกประกอบเป็นเส้นทางไฟล์ ไม่ได้อยู่ใน vhost
-- ไม่ได้อยู่ใน FPM pool และไม่ได้ใช้อ้างอิงอะไรทั้งสิ้น — เป็นภาระในการตั้งชื่อล้วน ๆ
-- ชื่อโดเมนคือสิ่งที่ผู้ดูแลใช้เรียกเว็บอยู่แล้วในทุกบริบท
--
-- **`users.display_name`** — เหตุผลเดียวกัน · ทุกที่ที่แสดงมันจะ fallback ไปที่ `username`
-- อยู่แล้วเมื่อว่าง แปลว่ามันไม่เคยเป็นข้อมูลที่ระบบต้องมี · ชื่อบัญชีเป็นสิ่งที่ผู้ใช้
-- พิมพ์ตอนล็อกอินและเป็นชื่อโฟลเดอร์บ้านของเขา จึงเป็นชื่อที่ตรงกับความจริงที่สุด
--
-- ไม่มีข้อมูลสำคัญหายไป: ทั้งสองคอลัมน์ไม่เคยถูกอ่านเพื่อตัดสินใจอะไร มีแต่ถูกพิมพ์ออกจอ
--
-- SQLite รุ่นที่ Ubuntu 24.04 ให้มารองรับ `DROP COLUMN` แล้ว (3.35+) จึงไม่ต้องสร้าง
-- ตารางใหม่แล้วย้ายข้อมูลเหมือน migration ก่อน ๆ

ALTER TABLE sites DROP COLUMN name;

ALTER TABLE users DROP COLUMN display_name;
