-- 0023_totp_replay — รหัส 2FA หนึ่งรหัสต้องใช้ได้ครั้งเดียว
--
-- **ปัญหาที่แก้:** `Totp::verify()` ยอมรับรหัสของช่วงเวลาก่อนหน้าและถัดไปอย่างละหนึ่ง
-- ช่วง (กันนาฬิกาคลาดเคลื่อน) แต่ไม่เคยจำว่ารหัสไหนถูกใช้ไปแล้ว · รหัสเดิมจึงใช้ซ้ำได้
-- ตลอดหน้าต่างราว 90 วินาที
--
-- ทำไมสำคัญกว่าที่เห็น: 2FA มีไว้กันกรณีที่**รหัสผ่านหลุดไปแล้ว** ผู้โจมตีที่เห็นรหัส
-- หกหลักได้ครั้งเดียว (แอบดูจอ, มัลแวร์อ่านคลิปบอร์ด, ฟิชชิงที่ผู้ใช้กรอกให้) จึงไม่ควร
-- ได้อะไรจากมันเลยหลังจากผู้ใช้ตัวจริงใช้รหัสนั้นเข้าระบบไปแล้ว — แต่เดิมเขามีเวลา
-- เหลืออีกเกือบนาทีครึ่งที่จะใช้รหัสเดียวกันนั้นซ้ำ
--
-- เก็บ "หมายเลขช่วงเวลาที่ใช้ล่าสุด" ไม่ใช่ตัวรหัส — ตัวเลขนี้เดินหน้าอย่างเดียว
-- เทียบง่าย และไม่ต้องเก็บความลับอะไรเพิ่ม · 0 = ยังไม่เคยใช้รหัสไหนเลย

