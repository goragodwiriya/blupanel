-- 0014_metrics_history — เก็บ metrics ย้อนหลังแบบลดความละเอียดตามอายุ (PLAN-V2 เฟส E6)
--
-- **ปัญหาที่แก้:** ตัวเลขทรัพยากรมีแต่ค่า ณ วินาทีนี้ (`GET /metrics` และ SSE) ผู้ดูแล
-- จึงตอบคำถามที่สำคัญที่สุดไม่ได้เลย: "เมื่อคืนตอนตีสามเกิดอะไรขึ้น" · หน้าจอของเฟส C
-- เผื่อที่สำหรับกราฟย้อนหลังไว้แล้วแต่ `GET /metrics/history` ยังไม่มีจริง
--
-- **ทำไมเก็บสามชั้นแทนที่จะเก็บทุกจุดตลอดไป:** เก็บทุกนาทีเป็นเวลา 90 วัน = 129,600 แถว
-- ต่อเครื่อง ซึ่งทำให้ไฟล์ฐานข้อมูลโตขึ้นเรื่อย ๆ และกราฟ 90 วันก็ไม่มีใครดูรายนาทีอยู่ดี
-- · เก็บสามชั้นแล้วรวมเมื่อข้อมูลเก่าลง ได้ ~2,000 แถวคงที่ต่อเครื่อง:
--
--   ชั้น (bucket)  ความละเอียด   เก็บนาน   จำนวนแถวสูงสุด
--   'minute'       1 นาที        24 ชม.    1,440
--   'hour'         1 ชั่วโมง     30 วัน      720
--   'day'          1 วัน         365 วัน     365
--
-- แผนเดิมเขียนไว้ว่า 1 นาที/24 ชม. → 5 นาที/7 วัน → 1 ชม./90 วัน · เปลี่ยนชั้นกลางจาก
-- "5 นาที" เป็น "1 ชั่วโมง" และขยายชั้นท้ายเป็นรายวัน/1 ปี เพราะคำถามที่ผู้ดูแลถามจริง
-- แบ่งเป็นสองแบบชัดเจน: "เมื่อวานตอนนั้นเกิดอะไร" (ต้องละเอียดระดับนาที ภายใน 24 ชม.)
-- กับ "เดือนนี้โตขึ้นเท่าไร" (รายวันพอ) — ชั้น 5 นาทีไม่ได้ตอบคำถามไหนที่อีกสองชั้นไม่ตอบ

CREATE TABLE metrics_history (
    id          INTEGER PRIMARY KEY,

    -- ชั้นความละเอียด · แถวเดียวกันของชั้นต่างกันอยู่ร่วมกันได้ ไม่ทับกัน
    bucket      TEXT    NOT NULL CHECK(bucket IN ('minute','hour','day')),

    -- เวลาเริ่มของช่วง (unix timestamp ที่ปัดลงตามชั้น) — ไม่ใช่เวลาที่บันทึก
    -- ปัดลงเพื่อให้การเขียนซ้ำในช่วงเดียวกันทับแถวเดิมแทนที่จะเพิ่มแถวใหม่
    bucket_at   INTEGER NOT NULL,

    -- ค่าเฉลี่ยของช่วง · เก็บเป็นเปอร์เซ็นต์ (0-100) ให้กราฟใช้ได้ตรง ๆ ไม่ต้องคำนวณต่อ
    cpu_percent    REAL NOT NULL DEFAULT 0,
    memory_percent REAL NOT NULL DEFAULT 0,
    disk_percent   REAL NOT NULL DEFAULT 0,
    load1          REAL NOT NULL DEFAULT 0,

    -- ค่าสูงสุดของ CPU ในช่วง — ค่าเฉลี่ยอย่างเดียวกลบพีคสั้น ๆ ที่เป็นต้นเหตุของ
    -- "เว็บช้าเป็นช่วง ๆ" จนมองไม่เห็นเลย ซึ่งเป็นเคสที่กราฟย้อนหลังมีไว้เพื่อตอบ
    cpu_peak       REAL NOT NULL DEFAULT 0,

    -- ไบต์จริง เก็บไว้ด้วยเพราะเปอร์เซ็นต์อย่างเดียวตอบไม่ได้ว่า "โตขึ้นกี่ GB"
    memory_used_bytes INTEGER NOT NULL DEFAULT 0,
    disk_used_bytes   INTEGER NOT NULL DEFAULT 0,

    -- จำนวนตัวอย่างที่รวมกันเป็นแถวนี้ — ใช้ถ่วงน้ำหนักตอนยุบขึ้นชั้นถัดไป
    -- ถ้าไม่มี การเฉลี่ยของค่าเฉลี่ยจะผิดเมื่อแต่ละแถวมีจำนวนตัวอย่างไม่เท่ากัน
    samples     INTEGER NOT NULL DEFAULT 1,

    created_at  INTEGER NOT NULL,

    -- หนึ่งช่วงมีได้แถวเดียวต่อชั้น — ทำให้ `INSERT ... ON CONFLICT DO UPDATE`
    -- รวมค่าเข้าแถวเดิมได้โดยไม่ต้องอ่านก่อนเขียน (กันการแข่งกันเขียนของสองโปรเซส)
    UNIQUE(bucket, bucket_at)
);

-- กราฟทุกอันถามด้วยรูปแบบเดียวกัน: ชั้นไหน ช่วงเวลาไหน เรียงตามเวลา
CREATE INDEX idx_metrics_history_range ON metrics_history(bucket, bucket_at);
