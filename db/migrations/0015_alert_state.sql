-- 0015_alert_state — สถานะการแจ้งเตือนล่าสุดของแต่ละเกณฑ์ (PLAN-V2 เฟส E6)
--
-- **ปัญหาที่ต้องแก้: การแจ้งเตือนที่ส่งซ้ำทุกนาทีคือการแจ้งเตือนที่ไม่มีใครอ่าน**
-- ดิสก์ที่เต็ม 90% จะเต็มอยู่อย่างนั้นจนกว่าจะมีคนไปลบไฟล์ · ถ้าส่งทุกรอบที่ตรวจเจอ
-- ผู้ดูแลจะได้ข้อความเดียวกัน 1,440 ครั้งต่อวันแล้วปิดการแจ้งเตือนภายในสัปดาห์เดียว
-- ซึ่งแย่กว่าไม่มีระบบแจ้งเตือนเลย เพราะเข้าใจว่าตัวเองมีระบบเฝ้าระวังอยู่
--
-- กฎที่ตารางนี้ทำให้เป็นจริง (ดู `Domain\AlertRules`):
--   1. แจ้งเมื่อ**เข้าสู่**สถานะผิดปกติ หรือเมื่อ**ระดับแย่ลง** (warn → critical) เท่านั้น
--   2. อยู่ในสถานะเดิม = เงียบ จนกว่าจะครบรอบเตือนซ้ำ (`notified_at` + ระยะเวลาที่ตั้งไว้)
--   3. กลับมาปกติ = แจ้งครั้งเดียวว่า "หายแล้ว" แล้วลบสถานะทิ้ง
--
-- ต่างจาก `disk_quota_state` ตรงที่นั่นเก็บระดับล่าสุดต่อ**ผู้ใช้** ส่วนนี่เก็บต่อ**เกณฑ์**
-- ของทั้งเครื่อง และต้องจำเวลาที่แจ้งล่าสุดด้วยเพื่อทำข้อ 2

CREATE TABLE alert_state (
    -- คีย์ของเกณฑ์ เช่น 'disk' · 'memory' · 'load' · 'service:nginx' · 'cert:example.com'
    -- ใส่เป้าหมายไว้ในคีย์เลย เพราะบริการคนละตัว/ใบรับรองคนละใบต้องนับแยกกัน
    alert_key   TEXT    NOT NULL PRIMARY KEY,

    -- ระดับล่าสุดที่แจ้งไป: warning | critical
    level       TEXT    NOT NULL CHECK(level IN ('warning','critical')),

    -- ค่าที่วัดได้ตอนแจ้ง — ใส่ในข้อความเตือนซ้ำให้เห็นว่าดีขึ้นหรือแย่ลงจากครั้งก่อน
    value       REAL    NOT NULL DEFAULT 0,

    first_at    INTEGER NOT NULL,   -- เข้าสู่สถานะผิดปกติครั้งแรกเมื่อไร
    notified_at INTEGER NOT NULL,   -- ส่งข้อความล่าสุดเมื่อไร (ใช้คุมรอบเตือนซ้ำ)
    updated_at  INTEGER NOT NULL
);
